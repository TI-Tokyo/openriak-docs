import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import {run,inspect} from './manager.mjs';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
test('a build generates and publishes a genuinely missing blog index using the real model',async()=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'semantic-real-missing-'));
 const target=JSON.parse(fs.readFileSync(path.join(repo,'tools/semantic-search/indexes.json')))[0];
 fs.mkdirSync(path.join(root,'tools/semantic-search'),{recursive:true});
 fs.writeFileSync(path.join(root,'tools/semantic-search/indexes.json'),JSON.stringify([target]));
 fs.cpSync(path.join(repo,target.source),path.join(root,target.source),{recursive:true});
 fs.mkdirSync(path.join(root,'content/static'),{recursive:true});
 fs.symlinkSync(path.join(repo,'content/static/semantic-search'),path.join(root,'content/static/semantic-search'),'dir');
 fs.mkdirSync(path.join(root,'tools/generated'),{recursive:true});
 fs.symlinkSync(path.join(repo,'tools/generated/semantic-cache'),path.join(root,'tools/generated/semantic-cache'),'dir');
 assert.equal(inspect(path.join(root,target.directory)).missing,true);
 fs.mkdirSync(path.join(root,'export'),{recursive:true});
 fs.writeFileSync(path.join(root,'export/semantic-source.json'),JSON.stringify({section:target.section,scope:target.scope,pages:[]}));
 const options={all:true,section:target.section,'site-dir':path.join(root,'export'),'publish-dir':path.join(root,'public')};
 await run(root,options);
 const m=inspect(path.join(root,target.directory)).manifest;
 assert.equal(m.articles,233);assert.ok(m.passages>0);
 assert.ok(fs.existsSync(path.join(root,'public',target.publicPath,m.vectors)));
 const modified=fs.statSync(path.join(root,target.directory,'manifest.json')).mtimeMs;
 await run(root,options);
 assert.equal(fs.statSync(path.join(root,target.directory,'manifest.json')).mtimeMs,modified,'An existing valid index must not be rebuilt');
 console.log('Generated missing index and reused it:',root);
});
