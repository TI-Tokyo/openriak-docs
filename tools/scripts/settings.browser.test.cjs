'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { chromium } = require('playwright');
const base = process.env.OPENRIAK_SETTINGS_TEST_BASE || 'http://127.0.0.1:1410/docs/';
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.OPENRIAK_BROWSER_EXECUTABLE || undefined });
  try {
    const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'] });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error' && message.text().includes('could not be initialized')) errors.push(message.text()); });
    const go = path => page.goto(new URL(path, base).href);
    await go('settings/');
    assert.equal(await page.locator('.settings-card').count(), 6);
    assert.equal(await page.locator('#main-content').evaluate(node => parseFloat(getComputedStyle(node).paddingTop) / parseFloat(getComputedStyle(document.documentElement).fontSize)), 0.75);
    assert.equal(await page.locator('[data-settings-sections] section').count(), 0);
    assert.equal(await page.getByRole('link', { name: 'Settings', exact: true, includeHidden: true }).count(), 2);
    await page.getByRole('searchbox', { name: 'Search settings' }).fill('version');
    assert.deepEqual(await page.locator('[data-settings-results] a strong').allTextContents(), Array(3).fill('Default documentation version'));
    assert.deepEqual(await page.locator('[data-settings-results] a span').allTextContents(), [
      'OS and architecture: OpenRiak KV',
      'OS and architecture: OpenRiak CS',
      'OS and architecture: OpenRiak TS'
    ]);
    assert.equal(await page.locator('[data-settings-results]').evaluate(node => getComputedStyle(node).position), 'absolute');
    await page.getByRole('searchbox', { name: 'Search settings' }).fill('ring size');
    await page.locator('[data-settings-results] a').first().click();
    assert.match(page.url(), /settings\/examples\/#examples-setting-/);
    assert.equal(await page.locator('[data-settings-sections] section').count(), 1);
    await page.getByLabel('Cluster naming pattern', { exact: true }).fill('custom-{letter}');
    await page.getByLabel('Cluster naming pattern', { exact: true }).blur();
    await page.getByLabel('Preferred ring size (power of two, at least 8)').fill('63');
    await page.getByLabel('Preferred ring size (power of two, at least 8)').blur();
    assert.match(await page.locator('[data-settings-status]').textContent(), /Could not save/);
    assert.equal(await page.evaluate(() => window.OpenRiakSettings.examples().ringSize), 64);
    await go('settings/appearance/');
    await page.getByRole('combobox', { name: 'Colour theme', exact: true }).selectOption('dark');
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    await page.getByRole('combobox', { name: 'Font size', exact: true }).selectOption('125');
    assert.equal(await page.locator('html').getAttribute('data-font-size'), '125');
    await page.waitForFunction(() => {
      const inputs = [...document.querySelectorAll('#appearance select')];
      return inputs.length === 4 && inputs.every(input => Math.abs(input.getBoundingClientRect().left - inputs[0].getBoundingClientRect().left) < 1);
    });
    await go('settings/code/');
    const codeTable = page.locator('.settings-code-table');
    const defaultRow = codeTable.locator('[data-code-settings-type="global"]');
    const bashRow = codeTable.locator('[data-code-settings-type="bash"]');
    const rubyRow = codeTable.locator('[data-code-settings-type="ruby"]');
    const checkDefaultPosition = async () => {
      assert.equal(await defaultRow.isVisible(), true);
      const header = await codeTable.getByRole('button', { name: 'Sort by Type', exact: true }).boundingBox();
      const defaults = await defaultRow.boundingBox();
      const filter = await codeTable.getByLabel('Filter Type', { exact: true }).boundingBox();
      assert.ok(header.y + header.height <= defaults.y);
      assert.ok(defaults.y + defaults.height <= filter.y);
    };
    await checkDefaultPosition();
    assert.equal(await page.getByLabel('Other language/type override').count(), 0);
    assert.equal(await codeTable.getByRole('button', { name: /^Sort by / }).count(), 6);
    assert.equal(await codeTable.getByRole('button', { name: 'Sort by Type', exact: true }).locator('..').getAttribute('aria-sort'), 'descending');
    assert.equal(await codeTable.locator('tbody tr').first().getAttribute('data-code-settings-type'), 'yaml');
    assert.equal(await rubyRow.getByLabel('Command Split for Ruby', { exact: true }).count(), 0);
    assert.equal(await bashRow.getByLabel('Command Split for Bash', { exact: true }).count(), 1);
    assert.equal(await codeTable.locator('tbody td:last-child').first().evaluate(node => getComputedStyle(node).textAlign), 'right');
    await defaultRow.getByLabel('Line Numbers for DEFAULT', { exact: true }).selectOption('true');
    await defaultRow.getByLabel('Expand for DEFAULT', { exact: true }).selectOption('true');
    await rubyRow.getByLabel('Preferred Ruby', { exact: true }).check();
    await bashRow.getByLabel('Preferred Bash', { exact: true }).check();
    assert.equal(await codeTable.locator('input[type="checkbox"]:checked').count(), 1);
    assert.equal(await rubyRow.getByLabel('Preferred Ruby', { exact: true }).isChecked(), false);
    await rubyRow.getByLabel('Wrap for Ruby', { exact: true }).selectOption('true');
    await rubyRow.getByRole('button', { name: 'Set to Default', exact: true }).click();
    assert.equal(await rubyRow.getByLabel('Wrap for Ruby', { exact: true }).inputValue(), '');
    assert.equal(await bashRow.getByLabel('Preferred Bash', { exact: true }).isChecked(), true);
    await bashRow.getByRole('button', { name: 'Set to Default', exact: true }).click();
    assert.equal(await codeTable.locator('input[type="checkbox"]:checked').count(), 0);
    await rubyRow.getByLabel('Preferred Ruby', { exact: true }).check();
    await rubyRow.getByLabel('Expand for Ruby', { exact: true }).selectOption('false');
    await defaultRow.getByRole('button', { name: 'Set All to Default', exact: true }).click();
    assert.equal(await codeTable.locator('input[type="checkbox"]:checked').count(), 0);
    assert.equal(await rubyRow.getByLabel('Expand for Ruby', { exact: true }).inputValue(), '');
    assert.equal(await defaultRow.getByLabel('Line Numbers for DEFAULT', { exact: true }).inputValue(), 'true');
    assert.equal(await defaultRow.getByLabel('Expand for DEFAULT', { exact: true }).inputValue(), 'true');
    await bashRow.getByLabel('Wrap for Bash', { exact: true }).selectOption('true');
    await rubyRow.getByLabel('Preferred Ruby', { exact: true }).check();
    await page.reload();
    assert.equal(await rubyRow.getByLabel('Preferred Ruby', { exact: true }).isChecked(), true);
    assert.equal(await bashRow.getByLabel('Wrap for Bash', { exact: true }).inputValue(), 'true');
    const clearFilters = () => codeTable.getByRole('button', { name: 'Clear filters', exact: true }).click();
    const visibleTypes = () => codeTable.locator('tbody tr:visible').evaluateAll(rows => rows.map(row => row.dataset.codeSettingsType));
    await codeTable.getByLabel('Filter Type', { exact: true }).fill('ruby');
    assert.deepEqual(await visibleTypes(), ['ruby']);
    await checkDefaultPosition();
    await page.reload();
    assert.deepEqual(await visibleTypes(), ['ruby']);
    await checkDefaultPosition();
    await clearFilters();
    for (const [column, value, expected] of [['Preferred', 'true', ['ruby']], ['Line Numbers', 'true', []], ['Wrap', 'true', ['bash']], ['Command Split', 'false', []], ['Expand', 'true', []]]) {
      await codeTable.getByLabel(`Filter ${column}`, { exact: true }).selectOption(value);
      assert.deepEqual(await visibleTypes(), expected);
      await checkDefaultPosition();
      await clearFilters();
    }
    for (const column of ['Type', 'Preferred', 'Line Numbers', 'Wrap', 'Command Split', 'Expand']) {
      const sorter = codeTable.getByRole('button', { name: `Sort by ${column}`, exact: true });
      await sorter.click();
      const heading = sorter.locator('..');
      const direction = await heading.getAttribute('aria-sort');
      await sorter.click();
      assert.notEqual(await heading.getAttribute('aria-sort'), direction);
      if (await heading.getAttribute('aria-sort') !== 'descending') await sorter.click();
      const first = await codeTable.locator('tbody tr:visible').first().getAttribute('data-code-settings-type');
      assert.equal(first, { Type: 'yaml', Preferred: 'ruby', 'Line Numbers': 'advancedconfig', Wrap: 'bash', 'Command Split': 'advancedconfig', Expand: 'advancedconfig' }[column]);
      await checkDefaultPosition();
    }
    await codeTable.getByLabel('Filter Command Split', { exact: true }).selectOption('na');
    const inapplicable = await visibleTypes();
    assert.ok(inapplicable.includes('ruby'));
    assert.ok(!inapplicable.some(type => ['global', 'bash', 'sh', 'shell'].includes(type)));
    await clearFilters();
    await codeTable.getByLabel('Filter Wrap', { exact: true }).selectOption('true');
    await codeTable.getByLabel('Filter Preferred', { exact: true }).selectOption('true');
    assert.deepEqual(await visibleTypes(), []);
    await checkDefaultPosition();
    await clearFilters();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.setViewportSize({ width: 1280, height: 720 });
    await go('openriak-kv/3.4.0/to-do/tests/example-values/');
    await page.evaluate(() => window.OpenRiakPageToolsReady);
    const block = page.locator('[data-code-block]').first();
    assert.match(await block.getAttribute('class'), /has-line-numbers/);
    assert.match(await block.getAttribute('class'), /is-wrapped/);
    assert.match(await block.locator('[data-code-highlight]').textContent(), /custom-A/);
    await block.locator('[data-code-copy]').click();
    const copied = await page.evaluate(() => navigator.clipboard.readText());
    assert.equal(copied, "printf '%s\\n' 'custom-A'\ncurl http://node-1.example.com:8098/ping");
    const downloadWait = page.waitForEvent('download');
    await block.locator('[data-code-download]').click();
    const download = await downloadWait;
    assert.equal(await fs.readFile(await download.path(), 'utf8'), copied);
    await page.locator('.site-section-trigger').click();
    await page.getByRole('link', { name: 'Settings', exact: true }).click();
    const returnLink = page.getByRole('link', { name: 'Return to documentation (OpenRiak KV 3.4.0: Personalized example values)', exact: true });
    const exampleUrl = new URL('openriak-kv/3.4.0/to-do/tests/example-values/', base).href;
    assert.equal(await returnLink.getAttribute('href'), exampleUrl);
    await go('settings/appearance/');
    assert.equal(await returnLink.getAttribute('href'), exampleUrl);
    await returnLink.click();
    await page.evaluate(() => { location.hash = 'example-anchor'; });
    // Going through the homepage must not replace the documentation destination.
    await go('');
    await page.locator('.site-section-trigger').click();
    await page.getByRole('link', { name: 'Settings', exact: true }).click();
    assert.equal(await returnLink.getAttribute('href'), `${exampleUrl}#example-anchor`);
    await returnLink.click();
    assert.equal(page.url(), `${exampleUrl}#example-anchor`);
    // Platform choices update documentation already open in another tab.
    await go('settings/platform/');
    assert.deepEqual(await page.locator('[data-settings-product]').evaluateAll(groups => groups.map(group => group.dataset.settingsProduct)), ['openriak-kv', 'openriak-cs', 'openriak-ts']);
    const kv = page.locator('[data-settings-product="openriak-kv"]');
    assert.equal(await kv.locator('legend img').count(), 1);
    const versionSelect = kv.getByLabel('Default documentation version for OpenRiak KV', { exact: true });
    assert.equal(await versionSelect.inputValue(), 'latest');
    await versionSelect.selectOption('3.4.0');
    await kv.getByRole('button', { name: 'Operating system for OpenRiak KV', exact: true }).click();
    await kv.locator('[data-os-id^="alpine-3.21-"]').first().click();
    await kv.locator('[data-download-architecture-select="alpine-3.21-aarch64"]').click();
    // A stale release preference must not override the currently selected OS/architecture.
    await page.evaluate(() => {
      const key = 'openriak-docs-architectures:openriak-kv';
      const preferences = JSON.parse(localStorage.getItem(key));
      const os = JSON.parse(document.getElementById('settings-platforms').textContent)
        .find(product => product.id === 'openriak-kv').versions
        .flatMap(version => version.operatingSystems || [])
        .find(os => os.id === 'alpine-3.21-aarch64');
      preferences[window.OpenRiakDocs.osReleaseKey(os)] = 'x86_64';
      localStorage.setItem(key, JSON.stringify(preferences));
    });
    await versionSelect.selectOption('latest');
    assert.equal(await kv.locator('[data-download-architecture-select="alpine-3.21-aarch64"]').evaluate(node => node.classList.contains('is-active')), true);
    await versionSelect.selectOption('3.4.0');
    const homepage = await context.newPage();
    await homepage.goto(base);
    await homepage.waitForFunction(() => document.querySelector('[data-home-project="openriak-kv"]').getAttribute('href').endsWith('/3.4.0/'));
    assert.equal(await homepage.locator('[data-home-project="openriak-kv"]').textContent(), 'Open 3.4.0 →');
    assert.equal(await homepage.locator('[data-home-project="openriak-kv"]').evaluate(node => getComputedStyle(node).fontWeight), '700');
    assert.equal(await homepage.locator('[data-home-project-latest="openriak-kv"]').isVisible(), true);
    assert.equal(await homepage.locator('[data-home-project-latest="openriak-kv"]').textContent(), 'Open Latest (3.4.1) →');
    assert.equal(await homepage.locator('[data-home-project-latest="openriak-kv"]').evaluate(node => getComputedStyle(node).fontWeight), '400');
    assert.match(await homepage.locator('[data-home-project-latest="openriak-kv"]').getAttribute('href'), /\/latest\/$/);
    const docs = await context.newPage();
    await docs.goto(new URL('openriak-kv/3.4.0/to-do/tests/example-values/', base).href);
    await docs.waitForFunction(() => document.documentElement.dataset.selectedOs === 'alpine-3.21-aarch64');
    await kv.getByRole('button', { name: 'Operating system for OpenRiak KV', exact: true }).click();
    await kv.locator('[data-os-id^="ubuntu-noble-"]').first().click();
    await kv.locator('[data-download-architecture-select="ubuntu-noble-amd64"]').click();
    await docs.waitForFunction(() => document.documentElement.dataset.selectedOs === 'ubuntu-noble-amd64');
    await docs.close();
    await versionSelect.selectOption('latest');
    await homepage.waitForFunction(() => document.querySelector('[data-home-project="openriak-kv"]').getAttribute('href').endsWith('/latest/'));
    assert.equal(await homepage.locator('[data-home-project-latest="openriak-kv"]').isVisible(), false);
    assert.equal(await homepage.locator('[data-home-project="openriak-kv"]').textContent(), 'Open Latest (3.4.1) →');
    assert.equal(await homepage.locator('[data-home-project="openriak-kv"]').evaluate(node => getComputedStyle(node).fontWeight), '700');
    await homepage.close();
    // Visited tables expose editable, scoped filters in Settings.
    await go('openriak-kv/3.4.0/to-do/tests/configuration-reference-table-test/');
    const tableFilterTitle = `${await page.title()} · Table 1`;
    const tableSearch = page.locator('[data-configuration-search]').first();
    await tableSearch.fill('ring');
    await go('settings/tables/');
    const storedSearch = page.getByRole('group', { name: tableFilterTitle, exact: true }).getByLabel('Search text', { exact: true });
    assert.equal(await storedSearch.inputValue(), 'ring');
    await storedSearch.fill('listener');
    await storedSearch.blur();
    await go('openriak-kv/3.4.0/to-do/tests/configuration-reference-table-test/');
    await page.waitForFunction(() => document.querySelector('[data-configuration-search]')?.value === 'listener');
    await go('settings/transfer/');
    for (const title of ['Export', 'Import', 'Reset']) assert.equal(await page.getByRole('heading', { name: title, exact: true }).count(), 1);
    await page.evaluate(() => localStorage.setItem('openriak-docs-feedback:test', 'keep'));
    const exportWait = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export settings', exact: true }).click();
    const exported = await exportWait;
    const backup = JSON.parse(await fs.readFile(await exported.path(), 'utf8'));
    assert.equal(backup.version, 1);
    assert.equal(backup.settings['openriak-docs-feedback:test'], undefined);
    const file = page.getByLabel('Import settings file');
    await file.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...backup, settings: { 'openriak-docs-theme': 'bad' } })) });
    assert.equal(await page.getByRole('button', { name: 'Apply import', exact: true }).isDisabled(), true);
    assert.equal(await page.evaluate(() => localStorage.getItem('openriak-docs-theme')), 'dark');
    await file.setInputFiles({ name: 'good.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...backup, settings: { 'openriak-docs-theme': 'light' } })) });
    await page.getByRole('button', { name: 'Apply import', exact: true }).click();
    assert.equal(await page.evaluate(() => localStorage.getItem('openriak-docs-font-size')), '125');
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
    await page.getByLabel('Import settings file').setInputFiles({ name: 'restore.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
    await page.getByLabel('Import mode').selectOption('replace');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Apply import', exact: true }).click();
    assert.equal(await page.evaluate(() => localStorage.getItem('openriak-docs-feedback:test')), 'keep');
    assert.equal(await page.evaluate(() => window.OpenRiakSettings.resolve('cluster', 1)), 'custom-A');
    await go('settings/');
    const clearAll = page.locator('[data-settings-clear]');
    const clearDialog = page.getByRole('dialog', { name: 'Clear all settings?' });
    const savedBeforeClear = await page.evaluate(() => JSON.stringify(window.OpenRiakSettings.snapshot()));
    await clearAll.click();
    assert.equal(await clearDialog.isVisible(), true);
    assert.equal(await clearDialog.getByRole('button', { name: 'Cancel', exact: true }).evaluate(node => node === document.activeElement), true);
    await page.keyboard.press('Escape');
    await clearDialog.waitFor({ state: 'hidden' });
    assert.equal(await clearAll.evaluate(node => node === document.activeElement), true);
    assert.equal(await page.evaluate(() => JSON.stringify(window.OpenRiakSettings.snapshot())), savedBeforeClear);
    await clearAll.click();
    await clearDialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await clearDialog.waitFor({ state: 'hidden' });
    assert.equal(await page.evaluate(() => JSON.stringify(window.OpenRiakSettings.snapshot())), savedBeforeClear);
    await clearAll.click();
    await clearDialog.getByRole('button', { name: 'Clear all', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-settings-status]').textContent === 'All settings cleared. Defaults restored.');
    assert.equal(await page.evaluate(() => window.OpenRiakSettings.resolve('cluster', 1)), 'my-example-cluster-A');
    assert.equal(await page.evaluate(() => window.OpenRiakSettings.read('openriak-docs-version:openriak-kv')), 'latest');
    assert.equal(await page.evaluate(() => localStorage.getItem('openriak-docs-code-language')), null);
    assert.equal(await page.evaluate(() => localStorage.getItem('openriak-docs-feedback:test')), 'keep');
    // Mobile sidebar and overview stay within the viewport.
    await page.setViewportSize({ width: 390, height: 844 });
    await go('settings/');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('[data-nav-toggle]').click();
    assert.equal(await page.getByRole('searchbox', { name: 'Search settings' }).isVisible(), true);
    assert.deepEqual(errors, []);
    await context.close();
    const noJS = await browser.newContext({ javaScriptEnabled: false });
    const fallback = await noJS.newPage();
    await fallback.goto(new URL('openriak-kv/3.4.0/to-do/tests/example-values/', base).href);
    assert.match(await fallback.locator('[data-code-highlight]').textContent(), /my-example-cluster-A/);
    assert.doesNotMatch(await fallback.locator('[data-code-highlight]').textContent(), /HAHAHUGO/);
    await noJS.close();
    console.log('Settings browser tests passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
